'use strict';
// Extractor edge cases found in the Phase 2 review. Expected costs are
// literals worked from published $/M prices, not calls to calculateCostUsd.
// Run: node --test tests/   (from the suite directory)

const assert = require('node:assert/strict');
const { describe, it, before, after } = require('node:test');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const LIB_DIR = process.env.TRACKER_LIB_DIR || path.resolve(__dirname, '../../../../lib');
const utils = require(path.join(LIB_DIR, 'tracker-utils.js'));

const OWN = '77777777-7777-4777-8777-777777777777';
const FOREIGN = '88888888-8888-4888-8888-888888888888';

let dir;
let n = 0;
before(() => { dir = fs.mkdtempSync(path.join(os.tmpdir(), 'tracker-edge-')); });
after(() => fs.rmSync(dir, { recursive: true, force: true }));

let clock = 0;
const ts = () => new Date(Date.UTC(2026, 9, 5, 12, 0, clock++)).toISOString();
const user = (content, extra = {}) => ({ type: 'user', sessionId: OWN, timestamp: ts(), message: { role: 'user', content }, ...extra });
const human = (content, extra = {}) => user(content, { origin: { kind: 'human' }, ...extra });
const asst = (id, model, usage, extra = {}) => ({ type: 'assistant', sessionId: OWN, timestamp: ts(),
  message: { id, role: 'assistant', model, content: [{ type: 'text', text: 'ok' }], usage }, ...extra });
const usage = (input, output, extra = {}) => ({ input_tokens: input, output_tokens: output,
  cache_read_input_tokens: 0, cache_creation_input_tokens: 0, ...extra });

function meta(records) {
  const p = path.join(dir, `${OWN}-${n++}.jsonl`);
  fs.writeFileSync(p, records.map(r => JSON.stringify(r)).join('\n') + '\n');
  return utils.extractTranscript(p, { fileSessionId: OWN }).meta;
}

const close = (actual, expected) =>
  assert.ok(Math.abs(actual - expected) < 1e-9, `${actual} ≉ ${expected}`);

describe('turns and first prompt across transcript eras', () => {
  it('task-notification origins alone do not switch off counting of plain prompts', () => {
    const m = meta([
      user('First real prompt'),
      asst('msg_1', 'claude-opus-4-6', usage(1, 10)),
      user('<task-notification>done</task-notification>', { origin: { kind: 'task-notification' } }),
      user('Second prompt'),
      asst('msg_2', 'claude-opus-4-6', usage(1, 10)),
    ]);
    assert.equal(m.numTurns, 2);
    assert.equal(m.firstPrompt, 'First real prompt');
    assert.ok(m.lastUserMsgAt);
  });

  it('a legacy session resumed under origin-era Claude Code keeps its first prompt and earlier turns', () => {
    const m = meta([
      user('Old prompt'),
      asst('msg_1', 'claude-opus-5-5', usage(1, 10)),
      human('New prompt'),
      user('[Request interrupted by user]'),
    ]);
    assert.equal(m.firstPrompt, 'Old prompt');
    assert.equal(m.numTurns, 2);
  });

  it('a plain prompt that mentions CLAUDE.md or agent_docs/ is still a prompt (noise filtering is for search only)', () => {
    const text = 'Read CLAUDE.md and agent_docs/tools.md, then fix the build';
    const m = meta([user(text), asst('msg_1', 'claude-opus-4-6', usage(1, 10)), user('<system-reminder>ctx</system-reminder>')]);
    assert.deepEqual([m.numTurns, m.firstPrompt], [1, text]);
  });

  it('a slash command counts as a prompt in files without origin fields too', () => {
    const m = meta([
      user('<local-command-caveat>Caveat: messages below were generated by local commands</local-command-caveat>', { isMeta: true }),
      user('<command-message>review</command-message>\n<command-name>/review</command-name>\n<command-args>src</command-args>'),
      user('<local-command-stdout>done</local-command-stdout>'),
    ]);
    assert.deepEqual([m.numTurns, m.firstPrompt], [1, '/review src']);
  });

  it('renders a slash-command first prompt as /name args', () => {
    const m = meta([human('<command-message>review</command-message>\n<command-name>/review</command-name>\n<command-args>src</command-args>')]);
    assert.equal(m.firstPrompt, '/review src');
  });

  it('leaves a typed prompt that merely mentions a command tag alone', () => {
    const text = 'Explain why <command-name>/foo</command-name> shows up in transcripts';
    assert.equal(meta([human(text)]).firstPrompt, text);
  });
});

describe('usage and cost', () => {
  it('prices 1-hour cache writes at 2x input, 5-minute at 1.25x', () => {
    // opus-5-5 input $4/M: 400 x 5.00 + 600 x 8.00 = 6,800 micro-dollars
    const m = meta([asst('msg_c', 'claude-opus-5-5', usage(0, 0, { cache_creation_input_tokens: 1000,
      cache_creation: { ephemeral_5m_input_tokens: 400, ephemeral_1h_input_tokens: 600 } }))]);
    close(m.totalCostUsd, 0.0068);
    close(utils.calculateCostUsd('claude-opus-5-5', 0, 0, 0, 1_000_000, 1_000_000), 8);
  });

  it('a streamed message is counted once, at its LAST record\'s usage', () => {
    // sonnet-5-5 $2/$10: msg_P final (3 in, 468 out) + msg_N (2 in, 20 out)
    const m = meta([
      asst('msg_P', 'claude-sonnet-5-5', usage(3, 1)),
      asst('msg_P', 'claude-sonnet-5-5', usage(3, 468)),
      asst('msg_N', 'claude-sonnet-5-5', undefined),
      asst('msg_N', 'claude-sonnet-5-5', usage(2, 20)),
    ]);
    assert.equal(m.outputTokens, 488);
    assert.equal(m.inputTokens, 5);
    close(m.totalCostUsd, (5 * 2 + 488 * 10) / 1e6);
    assert.equal(m.model, 'claude-sonnet-5-5');
  });

  it('cost-state with nothing after it is the whole cost', () => {
    const m = meta([asst('msg_A', 'claude-sonnet-5-5', usage(0, 100)), { type: 'cost-state', sessionId: OWN, totalCostUSD: 0.5 }]);
    close(m.totalCostUsd, 0.5);
    assert.equal(m.costSource, 'cost-state');
  });

  it('the last cost-state wins and only usage after it is added', () => {
    const m = meta([
      asst('msg_A', 'claude-sonnet-5-5', usage(0, 100)),
      { type: 'cost-state', sessionId: OWN, totalCostUSD: 0.5 },
      asst('msg_B', 'claude-sonnet-5-5', usage(0, 100)),
      { type: 'cost-state', sessionId: OWN, totalCostUSD: 0.9 },
      asst('msg_C', 'claude-sonnet-5-5', usage(0, 10)),
    ]);
    close(m.totalCostUsd, 0.9 + 10 * 10 / 1e6);
    assert.equal(m.costSource, 'cost-state+computed');
  });

  it('a message begun before a cost-state belongs to it, even if its records straddle it', () => {
    const m = meta([
      asst('msg_X', 'claude-sonnet-5-5', usage(0, 1)),
      { type: 'cost-state', sessionId: OWN, totalCostUSD: 0.7 },
      asst('msg_X', 'claude-sonnet-5-5', usage(0, 50)),
    ]);
    close(m.totalCostUsd, 0.7);
    assert.equal(m.costSource, 'cost-state');
  });

  it('<synthetic> records never count, even with usage', () => {
    const m = meta([asst('msg_s', '<synthetic>', usage(5, 999))]);
    assert.deepEqual([m.outputTokens, m.model, m.costSource], [0, null, null]);
  });
});

describe('titles and summaries', () => {
  it('falls back to agent-name for the title and the compact summary for the recap', () => {
    const recap = 'This session is being continued from a previous conversation. ' + 'z'.repeat(500);
    const m = meta([
      human('go'),
      user(recap, { isCompactSummary: true }),
      { type: 'agent-name', sessionId: OWN, agentName: 'fixer' },
    ]);
    assert.deepEqual([m.autoTitle, m.titleSource], ['fixer', 'agent-name']);
    assert.deepEqual([m.summary, m.summarySource, m.compactCount], [recap.slice(0, 400), 'compact', 1]);
  });

  it('an ai-title or agent-name addressed to another session is not this session\'s title', () => {
    const m = meta([
      human('go'),
      { type: 'ai-title', sessionId: FOREIGN, aiTitle: 'Not mine' },
      { type: 'agent-name', sessionId: FOREIGN, agentName: 'not-mine' },
    ]);
    assert.equal(m.autoTitle, null);
  });
});

describe('malformed records', () => {
  it('fields of the wrong type are ignored, never stored or thrown on', () => {
    const m = meta([
      human('go', { cwd: 42, gitBranch: { b: 1 } }),
      asst('msg_t', 'claude-sonnet-5-5', usage('7', '100')),
      { type: 'pr-link', sessionId: OWN, prUrl: { url: 'x' } },
      { type: 'last-prompt', sessionId: OWN, lastPrompt: 5 },
      { type: 'ai-title', sessionId: OWN, aiTitle: ['x'] },
      { type: 'cost-state', sessionId: OWN, totalCostUSD: '1.2' },
      { type: 'system', subtype: 'away_summary', sessionId: OWN, content: { text: 'x' } },
    ]);
    assert.deepEqual(
      [m.cwd, m.gitBranch, m.prUrl, m.lastPrompt, m.autoTitle, m.summary, m.costSource, m.totalCostUsd, m.outputTokens],
      [null, null, null, null, null, null, 'computed', 0, 0]);
  });

  it('extractSessionMeta returns null when the file cannot be read', () => {
    assert.equal(utils.extractSessionMeta(path.join(dir, 'missing.jsonl')), null);
  });
});
